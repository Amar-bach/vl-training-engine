"""Build the held-out SURDS validation eval set.

Steps:
  1. Read validation_qa.jsonl (already generated by surds_gen_qa.py)
  2. Stratified sample ~333/template (seed=42, target ~2000)
  3. Wrap into SFT schema (matching val_1k.jsonl format byte-for-byte for system prompt)
  4. Build meta parquet
  5. Gold-vs-gold self-score validation

Output:
  JSONL -> /mnt/data4/shasta/amar.amarjyoti/research_data/eval_runs/heldout_surdsval/heldout_surdsval.jsonl
  Meta  -> research/eval/heldout_val_meta.parquet
"""

import json
import math
import random
import sys
from pathlib import Path

import pandas as pd

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
QA_JSONL = Path("/mnt/data4/shasta/amar.amarjyoti/research_data/processed/surds_heldout/validation_qa.jsonl")
VAL_1K   = Path("/mnt/data4/shasta/amar.amarjyoti/research_data/vlm_cot_distill/sft_stageB/val_1k.jsonl")
OUT_DIR  = Path("/mnt/data4/shasta/amar.amarjyoti/research_data/eval_runs/heldout_surdsval")
OUT_JSONL = OUT_DIR / "heldout_surdsval.jsonl"
OUT_META  = Path(__file__).parent / "heldout_val_meta.parquet"

# ---------------------------------------------------------------------------
# Exact system prompt from val_1k line 1 (verified below)
# ---------------------------------------------------------------------------
SYSTEM_PROMPT = (
    "You are a spatial visual-reasoning assistant. First, ground every object "
    "referenced in the question by listing it inside a <grounding> block, each as "
    "<objN>label [x, y]</objN> with a normalized 0-1000 point. Then reason step by "
    "step inside a <think> block. Finally, give a concise, definitive response inside "
    "an <answer> block."
)

TEMPLATES = ["lr", "fb", "distance", "yaw", "xy2d", "depth"]
CATEGORICAL = {"lr", "fb", "distance", "yaw"}
CONTINUOUS  = {"xy2d", "depth"}


# ---------------------------------------------------------------------------
# Step 0: Verify system prompt is byte-identical to val_1k
# ---------------------------------------------------------------------------
def verify_system_prompt():
    with open(VAL_1K) as f:
        r = json.loads(f.readline())
    val1k_sys = r["messages"][0]["content"]
    if val1k_sys == SYSTEM_PROMPT:
        print(f"[OK] System prompt byte-identical to val_1k.")
    else:
        print("[WARN] System prompt DIFFERS from val_1k!")
        print(f"  val_1k    : {val1k_sys!r}")
        print(f"  hardcoded : {SYSTEM_PROMPT!r}")
    return val1k_sys


# ---------------------------------------------------------------------------
# Step 1: Load QA
# ---------------------------------------------------------------------------
def load_qa():
    data = []
    with open(QA_JSONL) as f:
        for line in f:
            line = line.strip()
            if line:
                data.append(json.loads(line))
    print(f"[Step 1] Loaded {len(data):,} QAs from {QA_JSONL}")
    counts = {}
    for d in data:
        t = d["template_type"]
        counts[t] = counts.get(t, 0) + 1
    for t in TEMPLATES:
        print(f"  {t}: {counts.get(t, 0):,}")
    return data


# ---------------------------------------------------------------------------
# Step 2: Stratified sample ~333 per template (seed=42, target ~2000)
# ---------------------------------------------------------------------------
def stratified_sample(data, target_per_template=333, seed=42):
    rng = random.Random(seed)
    by_template = {}
    for d in data:
        t = d["template_type"]
        by_template.setdefault(t, []).append(d)

    sampled = []
    print(f"\n[Step 2] Stratified sampling (target {target_per_template}/template, seed={seed}):")
    for t in TEMPLATES:
        pool = by_template.get(t, [])
        n = min(target_per_template, len(pool))
        chosen = rng.sample(pool, n)
        sampled.extend(chosen)
        note = "" if len(pool) >= target_per_template else f" (all — only {len(pool)} available)"
        print(f"  {t}: sampled {n:,} / {len(pool):,}{note}")
    print(f"  Total sampled: {len(sampled):,}")
    return sampled


# ---------------------------------------------------------------------------
# Step 3: Wrap into SFT schema
# ---------------------------------------------------------------------------
def wrap_sft(sample, system_prompt):
    """Convert a canonical QA record into the SFT messages schema."""
    image_path = sample["image_path"]
    prompt     = sample["prompt"]
    answer     = sample["answer"]

    user_content = "<image>" + prompt
    asst_content = f"<answer>{answer}</answer>"

    return {
        "messages": [
            {"role": "system",    "content": system_prompt},
            {"role": "user",      "content": user_content},
            {"role": "assistant", "content": asst_content},
        ],
        "images": [image_path],
    }


def write_jsonl(sampled, system_prompt, out_path):
    out_path.parent.mkdir(parents=True, exist_ok=True)
    missing = 0
    dropped = []
    rows = []
    for s in sampled:
        img = s["image_path"]
        if not Path(img).exists():
            missing += 1
            dropped.append(img)
            continue
        rows.append((s, wrap_sft(s, system_prompt)))

    print(f"\n[Step 3] Writing SFT JSONL:")
    print(f"  Total sampled: {len(sampled)}")
    print(f"  Missing images: {missing}")
    if dropped:
        print(f"  Dropped examples (first 5): {dropped[:5]}")
    print(f"  Writing {len(rows)} records -> {out_path}")

    with open(out_path, "w") as f:
        for _, rec in rows:
            f.write(json.dumps(rec) + "\n")

    return rows, missing


# ---------------------------------------------------------------------------
# Step 4: Build meta parquet
# ---------------------------------------------------------------------------
_DIMS_CACHE = {}


def _normalize_xy2d_gold(gold, image_path):
    """SURDS raw annotations give xy2d as PIXEL coords (0..W/0..H), but the model
    (and val_1k teacher gold) speak Qwen 0-1000 NORMALIZED coords. Convert pixel
    gold -> normalized so pred-vs-gold is in the same space. Idempotent-ish: only
    rescales when a coord exceeds 1000 (i.e. clearly pixels)."""
    import re
    from PIL import Image
    nums = re.findall(r"-?\d+\.?\d*", str(gold))
    if len(nums) < 2:
        return gold
    px, py = float(nums[0]), float(nums[1])
    if px <= 1000 and py <= 1000:
        return gold  # already normalized
    if image_path not in _DIMS_CACHE:
        _DIMS_CACHE[image_path] = Image.open(image_path).size
    W, H = _DIMS_CACHE[image_path]
    return f"[{round(px / W * 1000)}, {round(py / H * 1000)}]"


def build_meta(rows, out_path):
    records = []
    for idx, (s, rec) in enumerate(rows):
        template_type = s["template_type"]
        answer_kind = "continuous" if template_type in CONTINUOUS else "categorical"
        gold = s["answer"]
        if template_type == "xy2d":
            gold = _normalize_xy2d_gold(gold, s["image_path"])
        records.append({
            "idx":           idx,
            "image_path":    s["image_path"],
            "question":      s["prompt"],
            "gold_answer":   gold,
            "template_type": template_type,
            "answer_kind":   answer_kind,
        })

    df = pd.DataFrame(records)
    df.to_parquet(out_path, engine="pyarrow", index=False)
    print(f"\n[Step 4] Meta parquet: {len(df)} rows -> {out_path}")
    print(df["template_type"].value_counts(dropna=False).to_string())
    return df


# ---------------------------------------------------------------------------
# Step 5: Gold-vs-gold self-score
# ---------------------------------------------------------------------------
def gold_vs_gold(df):
    # Import score_surds from same directory
    sys.path.insert(0, str(Path(__file__).parent))
    from score_surds import score_one, parse_answer

    print(f"\n[Step 5] Gold-vs-gold self-score:")
    per_template = {}
    for _, row in df.iterrows():
        t    = row["template_type"]
        gold = row["gold_answer"]
        img  = row["image_path"]
        image_wh = None  # skip per-image size for speed; norm-space for xy2d

        result = score_one(gold, gold, t, image_wh=image_wh)
        per_template.setdefault(t, []).append(result["correct"])

    for t in TEMPLATES:
        results = per_template.get(t, [])
        acc = sum(results) / len(results) if results else 0.0
        flag = "" if acc >= 0.95 else " <-- INVESTIGATE"
        print(f"  {t:10s}: {acc:.1%} ({sum(results)}/{len(results)}){flag}")

    return per_template


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    print("=" * 70)
    print("Building held-out SURDS validation eval set")
    print("=" * 70)

    # Step 0: verify system prompt
    system_prompt = verify_system_prompt()

    # Step 1: load
    data = load_qa()

    # Step 2: stratified sample
    sampled = stratified_sample(data, target_per_template=333, seed=42)

    # Step 3: write SFT JSONL
    rows, n_missing = write_jsonl(sampled, system_prompt, OUT_JSONL)

    # Step 4: meta parquet
    df = build_meta(rows, OUT_META)

    # Step 5: self-score
    gold_vs_gold(df)

    # Summary
    print("\n" + "=" * 70)
    print("DONE")
    print(f"  JSONL:  {OUT_JSONL}  ({len(rows)} rows)")
    print(f"  Meta:   {OUT_META}  ({len(df)} rows)")
    print(f"  Missing/dropped images: {n_missing}")


if __name__ == "__main__":
    main()
